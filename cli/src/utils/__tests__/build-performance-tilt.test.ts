import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { evaluateStarlark, tiltAvailable } from "../../test-support/index.js";

// Behaviour of the Starlark planners that `flisk up` runs at Tiltfile load: the frontend build plan and the
// Tilt build concurrency. They run under Tilt's own Starlark interpreter, so these tests spawn Tilt.
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const framePlan = join(
  repoRoot,
  "engine/topologies/platform/docker/build/frontend_build_plan.star",
);
const concurrency = join(repoRoot, "engine/topologies/tilt/resources/build_concurrency.star");
const hasTilt = tiltAvailable();

/** Runs a Tiltfile body in a scratch project and returns the JSON value it wrote to `out.json`. */
function evaluate(file: string, body: string, files: Record<string, string> = {}): unknown {
  const result = evaluateStarlark(file, {
    args: `${body}\nlocal('cat > out.json', quiet = True, stdin = encode_json(RESULT))\n`,
    files,
  });
  if (result.status !== 0) throw new Error(`tilt failed: ${result.stderr || result.stdout}`);
  return JSON.parse(readFileSync(join(result.dir, "out.json"), "utf-8"));
}

const pkg = (scripts: Record<string, string>) => JSON.stringify({ name: "web", scripts });

describe.skipIf(!hasTilt)("frontend build plan", () => {
  const plan = (scripts: Record<string, string> | null) => {
    const files: Record<string, string> =
      scripts === null ? {} : { "web/package.json": pkg(scripts) };
    return evaluate(
      framePlan,
      `load(${JSON.stringify(framePlan)}, "frontend_build_plan")
RESULT = frontend_build_plan("web/package.json")`,
      files,
    ) as { build_cmd: string; typecheck: boolean; typecheck_cmd: string };
  };

  it("moves a non-emitting type-check out of the image and runs vite directly", () => {
    expect(plan({ build: "tsc --noEmit && vite build" })).toEqual({
      build_cmd: "bunx vite build",
      typecheck: true,
      typecheck_cmd: "bunx tsc --noEmit",
    });
  });

  it("keeps extra vite flags and a generated config the image copies", () => {
    const result = plan({
      build:
        "tsc --noEmit && vite build --mode production --config .autogenerated/vite.config.build.autogenerated.ts",
    });
    expect(result.build_cmd).toBe(
      "bunx vite build --mode production --config .autogenerated/vite.config.build.autogenerated.ts",
    );
    expect(result.typecheck).toBe(true);
  });

  it("keeps a plain emitting tsc in the image (its output may be used)", () => {
    expect(
      plan({
        build: "tsc && vite build --config .autogenerated/vite.config.build.autogenerated.ts",
      }),
    ).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
  });

  it("does not use a custom config the image does not copy", () => {
    expect(plan({ build: "tsc --noEmit && vite build --config vite.config.ts" }).typecheck).toBe(
      false,
    );
    expect(plan({ build: "tsc --noEmit && vite build --config=vite.config.ts" }).typecheck).toBe(
      false,
    );
  });

  it("leaves any other script unchanged", () => {
    expect(plan({ build: "vite build" }).typecheck).toBe(false);
    expect(plan({ build: "tsc --noEmit && vite build && node scripts/post.js" }).typecheck).toBe(
      false,
    );
    expect(plan({ build: "tsc -b && vite build" }).typecheck).toBe(false);
  });

  it("falls back to the default build when there is no build script or no package.json", () => {
    expect(plan({ start: "vite" })).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
    expect(plan(null)).toEqual({ build_cmd: "bun run build", typecheck: false, typecheck_cmd: "" });
  });

  it("handles scripts with whitespace around the chained operator", () => {
    expect(plan({ build: "  tsc --noEmit   &&   vite build  " })).toEqual({
      build_cmd: "bunx vite build",
      typecheck: true,
      typecheck_cmd: "bunx tsc --noEmit",
    });
  });

  it("preserves multiple vite build flags alongside custom autogenerated config", () => {
    const result = plan({
      build:
        "tsc --noEmit && vite build --base /subpath/ --emptyOutDir --config .autogenerated/vite.config.mjs --sourcemap",
    });
    expect(result.build_cmd).toBe(
      "bunx vite build --base /subpath/ --emptyOutDir --config .autogenerated/vite.config.mjs --sourcemap",
    );
    expect(result.typecheck).toBe(true);
    expect(result.typecheck_cmd).toBe("bunx tsc --noEmit");
  });

  it("supports --config= syntax with autogenerated config", () => {
    const result = plan({
      build: "tsc --noEmit && vite build --config=.autogenerated/vite.config.custom.ts",
    });
    expect(result.build_cmd).toBe("bunx vite build --config=.autogenerated/vite.config.custom.ts");
    expect(result.typecheck).toBe(true);
  });

  it("rejects chained scripts with three or more steps", () => {
    expect(plan({ build: "tsc --noEmit && vite build && cp -r dist/* ../public" })).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
  });

  it("rejects scripts where vite command is not vite build", () => {
    expect(plan({ build: "tsc --noEmit && vite preview" })).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
    expect(plan({ build: "tsc --noEmit && vite" })).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
  });

  it("keeps trailing --config flag when missing argument since it does not match leading path", () => {
    expect(plan({ build: "tsc --noEmit && vite build --config" })).toEqual({
      build_cmd: "bunx vite build --config",
      typecheck: true,
      typecheck_cmd: "bunx tsc --noEmit",
    });
  });

  it("rejects non-autogenerated config paths", () => {
    expect(plan({ build: "tsc --noEmit && vite build --config ../../vite.config.ts" })).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
    expect(plan({ build: "tsc --noEmit && vite build --config /etc/vite.config.ts" })).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
  });

  it("falls back to default plan when build script is empty or whitespace", () => {
    expect(plan({ build: "" })).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
    expect(plan({ build: "   " })).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
  });
});

describe.skipIf(!hasTilt)("Tilt build concurrency", () => {
  const max = (cpus: number, memoryBytes: number) =>
    evaluate(
      concurrency,
      `load(${JSON.stringify(concurrency)}, "compute_max_parallel_builds")
RESULT = compute_max_parallel_builds(${cpus}, ${memoryBytes})`,
    ) as number;
  const GIB = 1024 ** 3;

  it("reserves two CPUs and about 1.5 GiB per build, clamped to 3..8", () => {
    expect(max(8, Math.round(8.3 * GIB))).toBe(5); // memory allows 5
    expect(max(4, 16 * GIB)).toBe(3); // 2 CPUs left, clamped up to the minimum
    expect(max(32, 64 * GIB)).toBe(8); // plenty of room, clamped down to the maximum
    expect(max(12, 8 * GIB)).toBe(5); // memory is the limit
  });

  it("falls back to the minimum when the engine reports no CPUs or memory", () => {
    expect(max(0, 0)).toBe(3);
    expect(max(1, 64 * GIB)).toBe(3); // fewer CPUs than the reserve
    expect(max(32, GIB)).toBe(3); // less than one build's memory
  });

  it("rounds memory down to whole builds at the boundary", () => {
    expect(max(32, 6 * GIB)).toBe(4); // exactly four 1.5 GiB builds
    expect(max(32, 6 * GIB - 1)).toBe(3); // one byte short of four
    expect(max(10, 64 * GIB)).toBe(8); // CPUs give exactly the maximum
  });

  it("handles edge memory and CPU budgets at exact boundaries", () => {
    expect(max(5, 4.5 * GIB)).toBe(3); // 3 CPUs left, 3 builds of 1.5 GiB
    expect(max(6, 6 * GIB)).toBe(4); // 4 CPUs left, 4 builds of 1.5 GiB
    expect(max(7, 7.5 * GIB)).toBe(5); // 5 CPUs left, 5 builds of 1.5 GiB
    expect(max(8, 9 * GIB)).toBe(6); // 6 CPUs left, 6 builds of 1.5 GiB
    expect(max(9, 10.5 * GIB)).toBe(7); // 7 CPUs left, 7 builds of 1.5 GiB
    expect(max(10, 12 * GIB)).toBe(8); // 8 CPUs left, 8 builds of 1.5 GiB
  });

  it("clamps concurrency to minimum when CPUs or memory are severely constrained or negative", () => {
    expect(max(-2, 16 * GIB)).toBe(3);
    expect(max(8, -100)).toBe(3);
    expect(max(2, 64 * GIB)).toBe(3); // 2 - 2 = 0 CPUs
  });

  it("caps concurrency at maximum of 8 even with abundant resources", () => {
    expect(max(128, 512 * GIB)).toBe(8);
  });

  it("is bottlenecked by the smaller of CPU or memory budget", () => {
    expect(max(32, 4.5 * GIB)).toBe(3); // memory is the bottleneck: 4.5 GiB // 1.5 GiB = 3
    expect(max(5, 64 * GIB)).toBe(3); // CPU is the bottleneck: 5 - 2 = 3
  });
});

describe("Tilt build concurrency wiring", () => {
  // The override and the engine-unavailable branches run only inside a live Tilt load (they call update_settings),
  // so these checks pin the source they depend on.
  const source = readFileSync(concurrency, "utf-8");

  it("reads TDK_MAX_PARALLEL_BUILDS first and accepts only a positive integer", () => {
    expect(source).toContain("os.environ.get('TDK_MAX_PARALLEL_BUILDS'");
    expect(source).toContain("_is_positive_int(override)");
  });

  it("keeps Tilt's default and says why when docker info cannot be read", () => {
    expect(source).toContain("if resources == None:");
    expect(source).toContain("Tilt default (docker info unavailable");
  });

  it("calls update_settings exactly once", () => {
    expect(source.match(/update_settings\(/g)).toHaveLength(1);
  });

  it("defines expected build concurrency constants", () => {
    expect(source).toContain("MIN_PARALLEL_BUILDS = 3");
    expect(source).toContain("MAX_PARALLEL_BUILDS = 8");
    expect(source).toContain("RESERVED_CPUS = 2");
    expect(source).toContain("BUILD_MEMORY_BUDGET_BYTES = 1610612736");
  });

  it("formats docker info command query with CPU count and total memory", () => {
    expect(source).toContain("docker info --format '{{.NCPU}} {{.MemTotal}}'");
  });
});

describe("frontend build plan and concurrency static invariants", () => {
  const framePlanSource = readFileSync(framePlan, "utf-8");

  it("declares expected frontend build constants and standard command shapes", () => {
    expect(framePlanSource).toContain("DEFAULT_FRONTEND_BUILD_CMD = 'bun run build'");
    expect(framePlanSource).toContain("_TSC_FORMS = ['tsc --noEmit']");
    expect(framePlanSource).toContain("_IMAGE_CONFIG_DIR = '.autogenerated/'");
    expect(framePlanSource).toContain("_VITE_BUILD = 'vite build'");
  });

  it("simulates _is_positive_int logic across edge cases", () => {
    const isPositiveInt = (text: string): boolean =>
      text.length > 0 && /^\d+$/.test(text) && Number.parseInt(text, 10) > 0;

    expect(isPositiveInt("")).toBe(false);
    expect(isPositiveInt("0")).toBe(false);
    expect(isPositiveInt("-1")).toBe(false);
    expect(isPositiveInt("-50")).toBe(false);
    expect(isPositiveInt("abc")).toBe(false);
    expect(isPositiveInt("12a")).toBe(false);
    expect(isPositiveInt("3.14")).toBe(false);
    expect(isPositiveInt(" ")).toBe(false);

    expect(isPositiveInt("1")).toBe(true);
    expect(isPositiveInt("4")).toBe(true);
    expect(isPositiveInt("8")).toBe(true);
    expect(isPositiveInt("16")).toBe(true);
  });

  it("simulates compute_max_parallel_builds formula boundaries", () => {
    const minBuilds = 3;
    const maxBuilds = 8;
    const reservedCpus = 2;
    const memoryBudget = 1610612736;

    const compute = (cpus: number, mem: number) => {
      const byCpu = cpus - reservedCpus;
      const byMem = Math.floor(mem / memoryBudget);
      return Math.max(minBuilds, Math.min(maxBuilds, Math.min(byCpu, byMem)));
    };

    expect(compute(0, 0)).toBe(3);
    expect(compute(1, 100 * 1024 * 1024 * 1024)).toBe(3);
    expect(compute(6, 6 * memoryBudget)).toBe(4);
    expect(compute(8, 6 * memoryBudget)).toBe(6);
    expect(compute(10, 8 * memoryBudget)).toBe(8);
    expect(compute(64, 64 * memoryBudget)).toBe(8);
  });

  it("simulates frontend_build_plan script parsing invariants", () => {
    const simulatePlan = (script: string) => {
      const trimmed = script.trim();
      const steps = trimmed.split(" && ");
      if (steps.length !== 2) return { build_cmd: "bun run build", typecheck: false };
      const typecheckStep = steps[0].trim();
      const viteStep = steps[1].trim();
      if (typecheckStep !== "tsc --noEmit") return { build_cmd: "bun run build", typecheck: false };
      if (viteStep !== "vite build" && !viteStep.startsWith("vite build ")) {
        return { build_cmd: "bun run build", typecheck: false };
      }
      const extraArgs = viteStep.slice("vite build".length);
      const tokens = extraArgs.trim().split(/\s+/).filter(Boolean);
      for (let i = 0; i < tokens.length; i++) {
        let value = "";
        if (tokens[i] === "--config" && i + 1 < tokens.length) {
          value = tokens[i + 1];
        } else if (tokens[i].startsWith("--config=")) {
          value = tokens[i].slice("--config=".length);
        } else {
          continue;
        }
        if (!value.startsWith(".autogenerated/")) {
          return { build_cmd: "bun run build", typecheck: false };
        }
      }
      return { build_cmd: `bunx vite build${extraArgs}`, typecheck: true };
    };

    expect(simulatePlan("tsc --noEmit && vite build")).toEqual({
      build_cmd: "bunx vite build",
      typecheck: true,
    });
    expect(
      simulatePlan("tsc --noEmit && vite build --config .autogenerated/vite.config.ts"),
    ).toEqual({
      build_cmd: "bunx vite build --config .autogenerated/vite.config.ts",
      typecheck: true,
    });
    expect(
      simulatePlan("tsc --noEmit && vite build --config=.autogenerated/vite.config.ts"),
    ).toEqual({
      build_cmd: "bunx vite build --config=.autogenerated/vite.config.ts",
      typecheck: true,
    });
    expect(simulatePlan("tsc && vite build")).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
    });
    expect(simulatePlan("tsc --noEmit && vite build --config vite.config.ts")).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
    });
    expect(simulatePlan("tsc --noEmit && vite dev")).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
    });
    expect(simulatePlan("tsc --noEmit && vite build && extra")).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
    });
  });
});
